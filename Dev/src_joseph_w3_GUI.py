def _try_attach_console(pid, retries=8, delay=0.02):
    for attempt in range(retries):
        try:
            if AttachConsole(pid):
                return True
            try:
                FreeConsole()
            except Exception:
                pass
            if AttachConsole(pid):
                return True
        except Exception:
            pass
        _time.sleep(delay)
    return False

def _sanitize_chunk_local(text, max_append_bytes):
    if not text:
        return ""
    text = NOISY_MARKER_RE.sub("", text)
    text = CONTROL_CHARS_RE.sub("", text)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if len(text) > max_append_bytes:
        text = "[...TRUNCATED...]\n" + text[-max_append_bytes:]
    return text

def _read_console_buffer_via_ReadConsoleOutput(pid):
    if not _try_attach_console(pid, retries=8, delay=0.02):
        return None
    try:
        hStdOut = GetStdHandle(STD_OUTPUT_HANDLE)
        if not hStdOut:
            return None

        csbi = CONSOLE_SCREEN_BUFFER_INFO()
        if not GetConsoleScreenBufferInfo(hStdOut, ctypes.byref(csbi)):
            return None

        width = int(csbi.dwSize.X)
        height = int(csbi.dwSize.Y)
        if width <= 0 or height <= 0:
            return ""

        buf_size = COORD(width, height)
        buf_coord = COORD(0, 0)
        read_region = SMALL_RECT(0, 0, max(0, width - 1), max(0, height - 1))

        total_cells = width * height
        CharInfoArray = CHAR_INFO * total_cells
        buf = CharInfoArray()

        ok = ReadConsoleOutputW(
            hStdOut,
            ctypes.cast(buf, ctypes.POINTER(CHAR_INFO)),
            buf_size,
            buf_coord,
            ctypes.byref(read_region)
        )
        if not ok:
            return None

        text = ""
        for row in range(height):
            base = row * width
            row_buf = []
            for col in range(width):
                ci = buf[base + col]
                ch = ci.Char.UnicodeChar
                if not ch or ch == "\x00":
                    ch = " "
                row_buf.append(ch)

            row_txt = "".join(row_buf)
            row_txt = row_txt.rstrip(" \r")
            if row_txt == "":
               continue
            text = text + "\n" + row_txt + ""
        return text
    finally:
        try:
            FreeConsole()
        except Exception:
            pass

def _final_stable_console_snapshot(pid, timeout=1.6, check_interval=0.02):
    end = time.time() + timeout
    prev = None
    while time.time() < end:
        snap = _read_console_buffer_via_ReadConsoleOutput(pid)
        if snap is None:
            time.sleep(check_interval)
            continue
        if prev is not None and snap == prev:
            return snap
        prev = snap
        time.sleep(check_interval)
    return prev

def _set_clipboard_persistent_win(text: str):
    if not isinstance(text, str):
        text = str(text)
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")
    data = text + "\0"
    nbytes = len(data) * ctypes.sizeof(wintypes.WCHAR)
    hGlobal = GlobalAlloc(GMEM_MOVEABLE, nbytes)
    if not hGlobal:
        return False
    lp = GlobalLock(hGlobal)
    if not lp:
        try:
            GlobalUnlock(hGlobal)
        except Exception:
            pass
        return False
    try:
        ctypes.memmove(lp, data.encode("utf-16-le"), nbytes)
    finally:
        GlobalUnlock(hGlobal)
    if not OpenClipboard(None):
        return False
    try:
        EmptyClipboard()
        if not SetClipboardData(CF_UNICODETEXT, hGlobal):
            return False
    finally:
        CloseClipboard()
    return True

