def make_button_icon(kind="play", size=(16,16), fg=(30,30,30), bg=(255,255,255,0)):
    w, h = size
    img = Image.new("RGBA", (w, h), bg)
    draw = ImageDraw.Draw(img)
    pad = max(1, w // 6)
    if kind == "play":
        tri = [(pad, pad), (pad, h-pad), (w-pad, h//2)]
        draw.polygon(tri, fill=fg)
    elif kind == "stop":
        s = min(w, h) - 2*pad
        x0 = (w - s)//2
        y0 = (h - s)//2
        draw.rectangle([x0, y0, x0+s, y0+s], fill=fg)
    elif kind == "pause":
        bar_w = max(1, (w - 3*pad)//2)
        x1 = pad
        x2 = x1 + bar_w
        y0 = pad
        y1 = h - pad
        draw.rectangle([x1, y0, x2, y1], fill=fg)
        x3 = x2 + pad
        x4 = x3 + bar_w
        draw.rectangle([x3, y0, x4, y1], fill=fg)
    return ImageTk.PhotoImage(img)

