    def _format_elapsed(self, seconds: float) -> str:
        try:
            s = int(seconds)
            h = s // 3600
            m = (s % 3600) // 60
            sec = s % 60
            return f"{h:02d}:{m:02d}:{sec:02d}"
        except Exception:
            return "00:00:00"

    def _tick_elapsed(self):
        try:
            if self._start_time is None:
                self.elapsed_label.config(text="Elapsed: 00:00:00")
            else:
                elapsed = time.time() - self._start_time
                self.elapsed_label.config(text=f"Elapsed: {self._format_elapsed(elapsed)}")
        except Exception:
            pass
        finally:
            self._elapsed_after_id = self.root.after(1000, self._tick_elapsed)

