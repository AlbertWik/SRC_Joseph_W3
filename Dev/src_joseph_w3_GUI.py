    # Drag and drop handler: parses dropped data and adds files/folders
    def _on_drop_event(self, event):
        """
        Handler for DnD <<Drop>> from tkinterdnd2. The event.data typically contains a
        string with one or more file paths, each possibly enclosed in { } when paths contain spaces.
        Example: {C:\Path With Spaces\file.wav} {C:\Other\file2.wav}
        This function extracts paths and adds them via the same logic as add_files/add_folders.
        """
        try:
            data = getattr(event, "data", None)
            if not data:
                return "break"
            text = str(data)
            paths = []
            cur = ""
            in_brace = False
            for ch in text:
                if ch == "{":
                    in_brace = True
                    cur = ""
                elif ch == "}":
                    in_brace = False
                    if cur:
                        paths.append(cur)
                        cur = ""
                elif ch.isspace() and not in_brace:
                    if cur:
                        paths.append(cur)
                        cur = ""
                else:
                    cur += ch
            if cur:
                paths.append(cur)
            if not paths:
                return "break"
            existing = list(self.selected_inputs)
            seen = {str(p).lower() for p in existing}
            added_any = False
            for pstr in paths:
                try:
                    pclean = pstr.strip().strip('"')
                    p = Path(pclean)
                    key = str(p).lower()
                    if key not in seen:
                        existing.append(p)
                        seen.add(key)
                        added_any = True
                except Exception:
                    pass
            if added_any:
                self.selected_inputs = existing
                try:
                    first = Path(paths[0].strip().strip('"'))
                    if first.exists():
                        if first.is_dir():
                            self.cfg["last_folder"] = str(first)
                        else:
                            self.cfg["last_folder"] = str(first.parent)
                        save_config(self.cfg)
                except Exception:
                    pass
                self.refresh_input_list()
            return "break"
        except Exception:
            return "break"

