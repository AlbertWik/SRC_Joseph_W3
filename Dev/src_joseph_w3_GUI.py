    def build_job_list(self, dry=False):
        self.refresh_preview()
        human_key = self.cfg.get("format_flag", "")
        fmt_flag = FORMAT_FLAGS.get(human_key, human_key)
        sr = self.cfg.get("sr", "").strip()
        resample = self.cfg.get("resample") == "1"
        noclean = self.cfg.get("noclean") == "1"
        out_ext = self.cfg.get("output_ext", "wav").lstrip(".")
        out_folder = Path(self.cfg.get("output_folder") or RUNTIME_DIR)
        recursive = self.cfg.get("recursive") == "1"

        jobs = []
        inputs = list(self.selected_inputs)
        if not inputs:
            return jobs

        for src in inputs:
            try:
                if src.exists() and src.is_file():
                    out_name = src.stem + "." + out_ext
                    out_path = Path(out_folder) / out_name
                    cmd = build_command(src, out_path, {
                        "format_flag": fmt_flag,
                        "sr": sr,
                        "resample": "1" if resample else "0",
                        "noclean": "1" if noclean else "0"
                    })
                    jobs.append((cmd, src, out_path))
                elif src.exists() and src.is_dir():
                    files = discover_files(src, "*.*", recursive=bool(recursive))
                    for f in files:
                        try:
                            ext = f.suffix.lstrip(".").lower()
                            if ext not in OUTPUT_EXTS_SET:
                                continue
                            try:
                                rel = f.relative_to(src)
                            except Exception:
                                rel = Path(f.name)
                            target_dir = out_folder / src.name / rel.parent
                            out_name = f.stem + "." + out_ext
                            out_path = target_dir / out_name
                            cmd = build_command(f, out_path, {
                                "format_flag": fmt_flag,
                                "sr": sr,
                                "resample": "1" if resample else "0",
                                "noclean": "1" if noclean else "0"
                            })
                            jobs.append((cmd, f, out_path))
                        except Exception:
                            continue
                else:
                    ext = src.suffix.lstrip(".").lower()
                    if ext and ext in OUTPUT_EXTS_SET:
                        out_name = src.stem + "." + out_ext
                        out_path = Path(out_folder) / out_name
                        cmd = build_command(src, out_path, {
                            "format_flag": fmt_flag,
                            "sr": sr,
                            "resample": "1" if resample else "0",
                            "noclean": "1" if noclean else "0"
                        })
                        jobs.append((cmd, src, out_path))
                    else:
                        continue
            except Exception:
                continue

        return jobs

    def _check_targets_and_offer_removal(self, jobs):
        existing = [out for (_cmd, _inpf, out) in jobs if out.exists()]
        if not existing:
            return True
        sample = "\n".join(str(p) for p in existing[:8])
        more = "" if len(existing) <= 8 else f"\n... and {len(existing)-8} more"
        msg = ("The following target file(s) already exist:\n\n"
               f"{sample}{more}\n\n"
               "Do you want to automatically remove these existing files before processing? "
               "Yes will delete them; No will cancel processing.")
        rem = messagebox.askyesno("Existing target files", msg)
        if not rem:
            return False
        removed = 0
        for p in existing:
            try:
                p.unlink()
                removed += 1
            except Exception:
                pass
        self._insert_status(f"Removed {removed} existing target file(s).")
        return True

    def _compute_text_diff(self, txt1, txt2):
        min_len = min(len(txt1), len(txt2))
        i = 0
        while i < min_len and txt1[i] == txt2[i]:
            i += 1
        return txt2[i:]

    def start_processing(self):
        if self.running:
            self._insert_status("Processing already running")
            return
        self.queue_jobs = self.build_job_list()
        total = len(self.queue_jobs)
        if total == 0:
            self._insert_status("Nothing to process; add input(s) first")
            return

        ok = self._check_targets_and_offer_removal(self.queue_jobs)
        if not ok:
            self._insert_status("Processing cancelled by user (existing targets not removed).")
            return

        try:
            self.btn_start.config(state="disabled")
            self.btn_stop.config(state="normal")
        except Exception:
            pass

        self.processed_count = 0
        self.total_count = total
        self._update_counter()
        self._start_time = time.time()
        self._start_elapsed_timer()

        self.running = True
        self._insert_status(f"Starting {total} job(s)...")
        t = threading.Thread(target=self._process_queue, daemon=True)
        t.start()

