def discover_files(folder, pattern="*.*", recursive=True):
    p = Path(folder)
    if not recursive:
        if pattern in ("*.*", "*"):
            return [f for f in p.iterdir() if f.is_file()]
        else:
            return [f for f in p.iterdir() if f.is_file() and f.match(pattern)]
    if pattern in ("*.*", "*"):
        return [f for f in p.rglob("*") if f.is_file()]
    else:
        return [f for f in p.rglob(pattern) if f.is_file()]

def _find_window_for_pid(pid, timeout=2.0):
    end = _time.time() + timeout
    while _time.time() < end:
        found = []
        def _enum_proc(hwnd, lParam):
            try:
                if not IsWindowVisible(hwnd):
                    return True
                pid_dw = wintypes.DWORD()
                GetWindowThreadProcessId(hwnd, ctypes.byref(pid_dw))
                if pid_dw.value == pid:
                    found.append(hwnd)
            except Exception:
                pass
            return True
        enum_proc = WNDENUMPROC(_enum_proc)
        try:
            EnumWindows(enum_proc, 0)
        except Exception:
            pass
        if found:
            return found[0]
        _time.sleep(0.02)
    return None

