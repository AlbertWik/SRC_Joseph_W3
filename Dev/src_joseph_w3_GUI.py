        idx = getattr(self, "_inputs_menu_line", None)
        if idx is None:
            return
        if idx >= len(self.selected_inputs)-1:
            return
        item = self.selected_inputs.pop(idx)
        self.selected_inputs.append(item)
        self.refresh_input_list()
        self._inputs_menu_line = len(self.selected_inputs)-1

